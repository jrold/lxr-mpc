#!/usr/bin/env python3
"""board/include/volt_periphs.h from ST's STM32F765 device header: every
peripheral instance (GPIOA, USART3, DMA1_Stream4, ...) becomes a call to
volt_periph(), which hands out that peripheral's registers as plain memory
and lets the board see each access (board/board.c).

    python3 board/tools/gen_periphs.py

Copyright (C) 2026 Jason Rold. GPL-3.0-only.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEVICE = os.path.join(ROOT, "firmware", "Drivers", "CMSIS", "Device", "ST", "STM32F7xx", "Include", "stm32f765xx.h")
OUT = os.path.join(ROOT, "board", "include", "volt_periphs.h")

# #define GPIOA               ((GPIO_TypeDef *) GPIOA_BASE)
INSTANCE = re.compile(r"^#define\s+(\w+)\s+\(\((\w+)\s*\*\)\s*(\w+_BASE)\)\s*$")


def main():
    instances = []
    for line in open(DEVICE, encoding="latin-1"):
        m = INSTANCE.match(line.rstrip())
        if m:
            instances.append(m.groups())
    bases = []
    for _, _, base in instances:
        if base not in bases:
            bases.append(base)
    out = [
        "/* Generated by board/tools/gen_periphs.py from ST's stm32f765xx.h: do not edit. */",
        "#ifndef VOLT_PERIPHS_H",
        "#define VOLT_PERIPHS_H",
        "",
        "/* One id per register block; names sharing a block (aliases) share its id. */",
        "enum VoltPeriph {",
    ]
    out += ["    VP_%s," % b[:-len("_BASE")] for b in bases]
    out += [
        "    VP_DEVICE_COUNT",
        "};",
        "",
        "void *volt_periph(int id, unsigned size);",
        "",
    ]
    for name, typ, base in instances:
        out.append("#undef %s" % name)
        out.append("#define %s ((%s *)volt_periph(VP_%s, sizeof(%s)))" % (name, typ, base[:-len("_BASE")], typ))
    out += ["", "#endif", ""]
    open(OUT, "w").write("\n".join(out))
    print("%s: %d instances, %d register blocks" % (os.path.relpath(OUT, ROOT), len(instances), len(bases)))


if __name__ == "__main__":
    main()
