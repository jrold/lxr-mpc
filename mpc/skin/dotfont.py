def glyph(code):
    """The lit dots of character `code` as 8 rows of 5 booleans; anything
    outside printable ASCII is blank."""
    rows = _ROWS.get(chr(code) if 32 <= code < 127 else " ", _ROWS[" "]).split("|")
    return [[c == "#" for c in r] for r in rows]


def check():
    for ch, rows in _ROWS.items():
        parts = rows.split("|")
        if len(parts) != 8 or any(len(p) != 5 or set(p) - {".", "#"} for p in parts):
            raise SystemExit("dotfont: %r is not 5x8" % ch)
    missing = [chr(c) for c in range(32, 127) if chr(c) not in _ROWS]
    if missing:
        raise SystemExit("dotfont: no glyph for %s" % "".join(missing))


if __name__ == "__main__":
    check()
    for code in range(32, 127):
        print(chr(code))
        for r in glyph(code):
            print("".join("#" if b else "." for b in r))
